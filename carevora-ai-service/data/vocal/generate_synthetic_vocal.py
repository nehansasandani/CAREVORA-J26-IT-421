import pandas as pd, numpy as np, sys
from sklearn.decomposition import PCA
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC
from sklearn.pipeline import make_pipeline
from sklearn.model_selection import GroupKFold
from sklearn.metrics import accuracy_score, f1_score
df=pd.read_pickle('/tmp/crema_feats.pkl')
X=np.nan_to_num(df.iloc[:,3:].values.astype(float)); y=df[2].values; g=df[1].values
for a in np.unique(g):
    m=g==a; X[m]=(X[m]-X[m].mean(0))/(X[m].std(0)+1e-6)
Z=PCA(30,random_state=0).fit_transform(StandardScaler().fit_transform(X))
emos=sorted(np.unique(y)); gm=Z.mean(0)
mu={e:Z[y==e].mean(0) for e in emos}
W=np.vstack([Z[y==e]-mu[e] for e in emos]); L=np.linalg.cholesky(np.cov(W.T)+1e-6*np.eye(30))
def gen(sep,n_spk=300,per=20,spk_sd=0.5,seed=42):
    r=np.random.default_rng(seed); rows=[]
    for s in range(n_spk):
        off=r.normal(0,spk_sd,30)
        for e in emos:
            for _ in range(per):
                v=gm+sep*(mu[e]-gm)+off+L@r.normal(size=30)
                rows.append([f'S{s:03d}',e]+list(v))
    return pd.DataFrame(rows,columns=['speaker_id','emotion']+[f'pc{i+1}' for i in range(30)])
def ev(d):
    Xs=d.iloc[:,2:].values; ys=d.emotion.values; gs=d.speaker_id.values; a=[];f=[]
    for tr,te in GroupKFold(5).split(Xs,ys,gs):
        c=make_pipeline(StandardScaler(),SVC(C=10)).fit(Xs[tr],ys[tr]); p=c.predict(Xs[te])
        a.append(accuracy_score(ys[te],p)); f.append(f1_score(ys[te],p,average='macro'))
    return np.mean(a),np.mean(f)
for sep in [1.0,1.5,2.0,2.5]:
    print(sep, ev(gen(sep,n_spk=100,per=10)))

SEP=3.0
d=gen(SEP,n_spk=300,per=20)
print('final',SEP,ev(d))
import os; os.makedirs('/mnt/user-data/outputs/carevora_synthetic_vocal_v1',exist_ok=True)
o='/mnt/user-data/outputs/carevora_synthetic_vocal_v1/'
sp=sorted(d.speaker_id.unique()); rng=np.random.default_rng(1); rng.shuffle(sp)
split={s:('train' if i<210 else 'validation' if i<255 else 'test') for i,s in enumerate(sp)}
d['split']=d.speaker_id.map(split); d=d.round(4)
d.to_csv(o+'synthetic_vocal_emotion.csv',index=False)
for k in ['train','validation','test']: d[d.split==k].to_csv(o+k+'.csv',index=False)
